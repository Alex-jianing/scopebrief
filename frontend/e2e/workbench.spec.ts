import { expect, test } from '@playwright/test'

test('cross-project answer opens an immutable source and exposes its trace', async ({ page }, info) => {
  await page.goto('/')
  await expect(page).toHaveTitle('问据 · 团队知识工作台')
  await expect(page.getByRole('heading', { name: '跨项目上线评审' })).toBeVisible()
  await expect(page.getByRole('complementary', { name: '证据与轨迹' })).toHaveCount(0)
  await page.screenshot({ path: info.outputPath('workbench-start.png'), animations: 'disabled' })
  await page.getByRole('button', { name: '项目资料', exact: true }).click()
  await page.keyboard.press('/')
  await expect(page.getByLabel('问一个上线问题')).toBeFocused()
  const scope = page.getByRole('button', { name: '项目范围', exact: true })
  await scope.click()
  const north = page.getByRole('checkbox', { name: /北辰/ })
  const tide = page.getByRole('checkbox', { name: /潮汐/ })
  await expect(north).toBeChecked()
  await expect(tide).toBeChecked()
  await north.uncheck()
  await tide.uncheck()
  await expect(page.getByRole('button', { name: /跨项目放行/ })).toBeDisabled()
  await north.check()
  await tide.check()
  await page.keyboard.press('Escape')
  await expect(scope).toBeFocused()
  await expect(north).toBeHidden()
  await page.getByRole('button', { name: /跨项目放行/ }).click()
  await expect(page.getByText('可进入灰度', { exact: true })).toBeVisible()
  await expect(page.getByText('暂缓放行', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '引用 4', exact: true })).toBeVisible()
  await page.screenshot({ path: info.outputPath('workbench-answer.png'), animations: 'disabled' })
  const citation = page.getByRole('button', { name: '查看引用 1' })
  await citation.click()
  const dialog = page.getByRole('dialog', { name: '引用原文' })
  await expect(dialog.getByText('当前版本', { exact: true })).toBeVisible()
  await expect(dialog.locator('.highlighted')).toContainText('北辰可进入 10% 灰度')
  await page.screenshot({ path: info.outputPath('workbench-source.png'), animations: 'disabled' })
  await page.keyboard.press('Escape')
  await expect(citation).toBeFocused()
  await page.getByRole('button', { name: '运行轨迹' }).click()
  await expect(page.getByText('定向补查', { exact: true })).toBeVisible()
  await expect(page.getByText('验证结果', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByText('可进入灰度', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '新建问答' }).click()
  const composer = page.getByLabel('问一个上线问题')
  await expect(composer).toBeFocused()
  await expect(composer).toHaveValue('')
  await page.getByRole('region', { name: '最近运行' }).getByRole('button', { name: /今晚北辰和潮汐/ }).click()
  await expect(page.getByRole('button', { name: '引用 4', exact: true })).toBeVisible()
})

test('reviewer access and publishing work through real sessions', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '项目资料' }).click()
  await expect(page.getByRole('button', { name: '北辰 · 灰度上线评审', exact: true })).toBeVisible()
  await expect(page.getByText('铸桥 · 迁移准入评审')).toHaveCount(0)
  await expect(page.getByRole('button', { name: '发布资料' })).toHaveCount(0)
  await page.getByText('项目成员', { exact: true }).click()
  await page.getByRole('button', { name: '切换为评审者' }).click()
  await page.getByRole('button', { name: '项目范围', exact: true }).click()
  await expect(page.getByRole('checkbox', { name: /铸桥/ })).toBeVisible()
  await page.keyboard.press('Escape')

  await page.getByRole('button', { name: '项目资料' }).click()
  await page.getByRole('checkbox', { name: '包含历史版本' }).check()
  await expect(page.getByRole('row').filter({ hasText: '北辰 · 灰度上线评审' })).toHaveCount(2)
  await page.getByRole('button', { name: '发布资料' }).click()
  const dialog = page.getByRole('dialog', { name: '发布 Markdown 资料' })
  await dialog.getByLabel('文档键').fill('e2e-runbook')
  await dialog.getByLabel('标题').fill('北辰 · 演练备注')
  await dialog.getByLabel('Markdown 正文').fill('## 演练代号\n通用搜索词 RAVEN-409。')
  await dialog.getByRole('button', { name: '确认发布' }).click()
  await expect(page.getByText('已发布 北辰 · 演练备注 · v1', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '评审问答' }).click()
  await page.getByLabel('问一个上线问题').fill('北辰演练代号 RAVEN-409')
  await page.getByRole('button', { name: '查证', exact: true }).click()
  await expect(page.getByText('通用搜索词 RAVEN-409。', { exact: false })).toBeVisible()
})

test('regression report filters differences and downloads JSON', async ({ page }, info) => {
  await page.goto('/')
  await page.getByRole('button', { name: '回归评测' }).click()
  await page.getByRole('button', { name: '运行评测' }).click()
  await expect(page.getByRole('heading', { name: '用例明细' })).toBeVisible()
  const all = await page.locator('tbody tr').count()
  expect(all).toBeGreaterThan(20)
  await page.getByRole('checkbox', { name: '只看结果差异' }).check()
  expect(await page.locator('tbody tr').count()).toBeLessThan(all)
  await page.screenshot({ path: info.outputPath('benchmark.png'), animations: 'disabled' })
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出 JSON' }).click()
  expect((await download).suggestedFilename()).toBe('scopebrief-evaluation.json')
})

test('mobile workbench fits its viewport and handles missing evidence', async ({ page }, info) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await page.getByRole('button', { name: /缺证据情形/ }).click()
  await expect(page.getByText('当前范围内缺少有效证据')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }))
  await page.screenshot({ path: info.outputPath('mobile.png'), animations: 'disabled', fullPage: true })
  await page.getByRole('button', { name: '查看证据' }).click()
  const evidence = page.getByRole('complementary', { name: '证据与轨迹' })
  await expect(evidence).toBeFocused()
  await expect(evidence).toBeInViewport()
})
